// 시드 고정 난수 (월드마다 같은 맵)
function seeded(seed) {
  let s = seed >>> 0;
  return () => {
    s = (s * 1664525 + 1013904223) >>> 0;
    return s / 4294967296;
  };
}

function buildLevel(wi) {
  const w = WORLDS[wi];
  const rnd = seeded(1000 + wi * 7919);
  const bag = [];
  Object.keys(w.weights).forEach((k) => { for (let i = 0; i < w.weights[k]; i++) bag.push(k); });
  const order = ['start'];
  let last = '';
  for (let i = 0; i < w.chunks; i++) {
    if (i === Math.floor(w.chunks / 2)) order.push('check');
    let k;
    do { k = bag[Math.floor(rnd() * bag.length)]; } while (k === last);
    order.push(k);
    last = k;
  }
  order.push('end');
  const rows = Array.from({ length: 12 }, () => '');
  order.forEach((k) => CHUNKS[k].forEach((line, r) => { rows[r] += line; }));
  return rows;
}
